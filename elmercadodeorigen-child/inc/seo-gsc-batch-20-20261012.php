	'the_content',
	static function ( $content ) {
		if ( ! is_string( $content ) || is_admin() || is_feed() || ! is_singular( 'post' ) || ! in_the_loop() || ! is_main_query() ) {
			return $content;
		}
		$path = function_exists( 'elmercado_gsc_current_path_010313' ) ? elmercado_gsc_current_path_010313() : '';
		$all  = elmercado_gsc_batch_20_links_20261012();
		if ( ! isset( $all[ $path ] ) || false !== strpos( $content, 'data-emo-gsc-links-20' ) ) {
			return $content;
		}
		$items = array();
		foreach ( $all[ $path ] as $link ) {
			$target = $link[0];
			if ( $target === $path || false !== strpos( $content, $target ) || ( 0 === strpos( $path, '/en/' ) ) !== ( 0 === strpos( $target, '/en/' ) ) ) {
				continue;
			}
			$items[] = '<li><a href="' . esc_url( home_url( $target ) ) . '">' . esc_html( $link[1] ) . '</a></li>';
		}
		if ( ! $items ) {
			return $content;
		}
		$english = 0 === strpos( $path, '/en/' );
		$aside = '<aside data-emo-gsc-links-20="1" class="emo-gsc-related-guides" aria-label="' . esc_attr( $english ? 'Related guides' : 'Guías relacionadas' ) . '">'
			. '<p><strong>' . esc_html( $english ? 'More practical guides' : 'Más guías prácticas' ) . '</strong></p><ul>' . implode( '', $items ) . '</ul></aside>';
		// Antes de los productos dinámicos; mantener intactos los anuncios in-article.
		if ( preg_match( '~<(?:section|div)\\b[^>]*\\bemo-related-products-dynamic\\b~iu', $content, $match, PREG_OFFSET_CAPTURE ) ) {
			$offset = (int) $match[0][1];
			return substr( $content, 0, $offset ) . $aside . substr( $content, $offset );
		}
		return $content . $aside;
	},
	38
